#!/usr/bin/env python3
"""Merge framework component schemas and business migrations for manual PostgreSQL initialization."""

from __future__ import annotations

import argparse
import hashlib
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "sql/framework-schema.sql"


def render_schema() -> tuple[bytes, int]:
    components = sorted(ROOT.glob("loadup-components/**/src/main/resources/db/schema/**/*.sql"))
    if not components:
        raise ValueError("No component schema templates found")
    migrations = sorted(
        ROOT.glob("loadup-modules/**/src/main/resources/db/migration/framework/*/V*.sql"),
        key=lambda path: (int(path.name[1:].split("__", 1)[0]), path.as_posix()),
    )
    if not migrations:
        raise ValueError("No business module migrations found")
    sources = components + migrations

    sections = [
        b"-- Generated by tools/export-schema.py. Do not edit this file directly.\n"
        b"-- PostgreSQL framework initialization: component schemas, then versioned business module migrations.\n"
        b"-- Import into a fresh empty schema only; this file is not replay-safe.\n"
        b"-- Uses the connection's search_path; creates no database or schema.\n"
        b"-- Does not create or update Flyway history.\n"
    ]
    for source in sources:
        content = source.read_bytes()
        if not content.strip():
            raise ValueError(f"Empty SQL source: {source.relative_to(ROOT)}")
        content.decode("utf-8")
        relative = source.relative_to(ROOT).as_posix()
        digest = hashlib.sha256(content).hexdigest()
        sections.append(f"\n-- BEGIN {relative}\n-- SHA-256: {digest}\n".encode("utf-8"))
        sections.append(content)
        if not content.endswith(b"\n"):
            sections.append(b"\n")
        sections.append(f"-- END {relative}\n".encode("utf-8"))
    return b"".join(sections), len(sources)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if the merged SQL is missing or stale; write nothing")
    args = parser.parse_args()
    try:
        expected, count = render_schema()
        current = OUTPUT.read_bytes() if OUTPUT.is_file() else None
        if args.check:
            if current != expected:
                print("Merged schema is missing or stale. Run: python3 tools/export-schema.py", file=sys.stderr)
                return 1
            print(f"Merged schema is in sync ({count} SQL files).")
        else:
            if current != expected:
                OUTPUT.parent.mkdir(parents=True, exist_ok=True)
                OUTPUT.write_bytes(expected)
            print(f"Merged {count} SQL files into {OUTPUT}")
    except (OSError, ValueError) as error:
        print(f"Cannot export framework initialization SQL: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
